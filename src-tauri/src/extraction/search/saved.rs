/// §2.1 bounds.
pub const MAX_SAVED_BYTES: i64 = 32 * 1024 * 1024;
pub const MAX_JSON_FIELD_BYTES: i64 = 4 * 1024 * 1024;
pub const MAX_TEXT_FIELD_BYTES: i64 = 1024 * 1024;
pub const MAX_RECORDS: usize = 200_000;
/// A material title longer than this isn't read; the group says "Untitled
/// material". Titles are stored once per material, clipped (§2.1).
pub const MAX_TITLE_BYTES: i64 = 4096;
/// Ids are generated by the app; anything longer isn't one of its rows.
pub const MAX_ID_BYTES: i64 = 256;

/// The saved-content categories `contentTypes` may name (§3).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Categories {
    pub guides: bool,
    pub cards: bool,
    pub practice: bool,
    pub notes: bool,
    pub questions: bool,
    pub homework: bool,
}

impl Categories {
    pub fn any(&self) -> bool {
        self.guides || self.cards || self.practice || self.notes || self.questions || self.homework
    }
}

/// What a request asks of saved content.
#[derive(Debug, Clone)]
pub struct SavedRequest {
    pub categories: Categories,
    /// The materials the filters select; guides, cards, practice and
    /// linked questions follow these (§3).
    pub material_ids: Vec<String>,
    pub material_filters_active: bool,
}

